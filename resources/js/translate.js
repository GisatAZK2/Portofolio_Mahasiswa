const DEFAULT_LANG = 'id';
const SUPPORTED_LANGS = ['id', 'en'];

let translateElements = [];

// Cache semua element yang butuh translate
function cacheTranslateElements() {
  translateElements = Array.from(
    document.querySelectorAll('[data-translate], [data-translate-placeholder]')
  );
}

// Ambil locale dari URL (kalau ada prefix /id/ atau /en/)
function getLocaleFromUrl() {
  const pathSegments = window.location.pathname.split('/').filter(Boolean);
  return SUPPORTED_LANGS.includes(pathSegments[0]) ? pathSegments[0] : null;
}

// Simpan locale ke localStorage + cookie 'lang' (dibaca middleware SetLocale di server)
function persistLocale(locale) {
  localStorage.setItem('lang', locale);
  const days = 365;
  const expires = new Date(Date.now() + days * 24 * 60 * 60 * 1000).toUTCString();
  document.cookie = `lang=${locale}; expires=${expires}; path=/; SameSite=Lax`;
}

// Tentukan locale aktif:
// 1. localStorage (pilihan eksplisit user) — paling otoritatif di sisi client,
//    supaya pindah ke halaman tanpa prefix locale (mis. /admin/users) tidak
//    "lupa" bahasa yang sudah dipilih.
// 2. Prefix URL (/id/... atau /en/...) — dipakai kalau belum ada preferensi tersimpan.
// 3. Fallback DEFAULT_LANG.
let currentLang = localStorage.getItem('lang') || getLocaleFromUrl() || DEFAULT_LANG;

// Apply translation ke semua element
function applyTranslations() {
  const langData = translations[currentLang] || translations[DEFAULT_LANG];

  const translateKey = (page, key) => {
    return langData?.[page]?.[key]
      || translations[DEFAULT_LANG]?.[page]?.[key]
      || key;
  };

  translateElements.forEach(el => {
    const page = el.dataset.translatePage || 'sidebar';
    const key = el.dataset.translate;

    // Text
    if (page && key) {
      const text = translateKey(page, key);
      // Hanya update jika berbeda
      if (text !== el.textContent) {
        el.textContent = text;
      }
    }

    // Placeholder
    const placeholderKey = el.dataset.translatePlaceholder;
    if (placeholderKey) {
      const placeholderText = translateKey(page, placeholderKey);
      if (placeholderText && placeholderText !== el.getAttribute('placeholder')) {
        el.setAttribute('placeholder', placeholderText);
      }
    }
  });

  // Set dropdown language
  const select = document.getElementById('languageSelect');
  if (select && select.value !== currentLang) {
    select.value = currentLang;
  }
}

// Init saat page load
document.addEventListener('DOMContentLoaded', () => {
  // Pastikan localStorage & cookie konsisten dengan currentLang yang sudah ditentukan di atas.
  persistLocale(currentLang);

  const select = document.getElementById('languageSelect');
  if (select) {
    select.value = currentLang;
    select.addEventListener('change', changeLanguage);
  }

  cacheTranslateElements();
  applyTranslations();
});

// Ganti bahasa: simpan preferensi lalu reload di halaman yang sama
// (tidak perlu pindah ke URL berprefix locale; server membaca cookie 'lang').
window.changeLanguage = function () {
    const select = document.getElementById('languageSelect');
    const locale = select.value;

    persistLocale(locale); // tetap simpan cookie & localStorage

    const url = new URL(window.location.href);
    // Hapus prefix locale dari path (jika ada)
    let pathname = url.pathname;
    pathname = pathname.replace(/^\/(id|en)(\/|$)/, '/$2'); // simpan slash setelahnya
    // Jika pathname kosong (root), biarkan '/'
    if (pathname === '') pathname = '/';
    url.pathname = pathname;

    // Set query parameter locale
    url.searchParams.set('locale', locale);

    window.location.href = url.toString();
};

// 🔥 Penting: untuk dynamic content (Livewire, AJAX, dll)
window.refreshTranslations = function () {
  cacheTranslateElements();
  applyTranslations();
};

// Global access
window.translations = translations;
window.currentLang = currentLang;